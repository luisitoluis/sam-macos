mod tui;
mod worker;

pub fn main() -> std::process::ExitCode {
    match tui::run() {
        Ok(()) => std::process::ExitCode::SUCCESS,
        Err(err) => {
            eprintln!("{err}");
            std::process::ExitCode::FAILURE
        }
    }
}
